export function getModelCatalogEntry(archId: string): ModelCatalogSpec | undefined {
  return MODEL_CATALOG.find((item) => item.id === archId || item.architecture === archId);
}

export function getPreprocessModeForArchitecture(archId: string): PreprocessMode {
  const entry = getModelCatalogEntry(archId);
  return entry?.preprocessMode ?? 'zero_one';
}

export function isPretrainedTransferArchitecture(archId: string): boolean {
  const entry = getModelCatalogEntry(archId);
  return Boolean(
    entry &&
      entry.backendEngine === 'tfjs_browser' &&
      entry.pretrainedAvailable &&
      entry.capabilities.training &&
      !entry.isGraphModel
  );
}

export function getCatalogModelsForTask(
  task: AnyTaskType,
  options?: { trainableOnly?: boolean }
): ModelCatalogSpec[] {
  return MODEL_CATALOG.filter((m) => {
    if (!m.supportedTasks.includes(task)) return false;
    if (options?.trainableOnly && !m.capabilities.training) return false;
    return true;
  });
}

export function checkWorkerCompatibility(
  spec: ModelCatalogSpec,
  workerCaps?: PythonWorkerCapabilities | null
): { compatible: boolean; missingPackages: string[]; reason: string } {
  if (spec.backendEngine === 'tfjs_browser') {
    return { compatible: true, missingPackages: [], reason: 'Runs natively in browser via TF.js' };
  }
  if (!workerCaps || !workerCaps.reachable) {
    return {
      compatible: false,
      missingPackages: spec.requiredPythonPackages,
      reason: 'External Python AI worker is offline or not configured.',
    };
  }
  const missing: string[] = [];
  for (const pkg of spec.requiredPythonPackages) {
    if (pkg === 'torch' && !workerCaps.torchInstalled) missing.push('torch');
    else if (pkg === 'torchvision' && !workerCaps.torchvisionInstalled) missing.push('torchvision');
    else if (pkg === 'ultralytics' && !workerCaps.ultralyticsInstalled) missing.push('ultralytics');
    else if (pkg === 'timm' && !workerCaps.timmInstalled) missing.push('timm');
    else if (pkg === 'transformers' && !workerCaps.transformersInstalled)
      missing.push('transformers');
    else if (pkg === 'onnxruntime' && !workerCaps.onnxruntimeInstalled) missing.push('onnxruntime');
    else if (pkg === 'paddleocr' && !workerCaps.paddleocrInstalled) missing.push('paddleocr');
  }
  if (missing.length > 0) {
    return {
      compatible: false,
      missingPackages: missing,
      reason: `Worker missing required Python libraries: ${missing.join(', ')}`,
    };
  }
  return { compatible: true, missingPackages: [], reason: 'Worker dependencies verified.' };
}

export function buildSameDatasetComparisonRows(
  trainedModels: TrainedModel[],
  reports: EvaluationReport[],
  projectId: string,
  datasetId: string,
  datasetVersion: number,
  split: EvaluationSplitTarget
): ModelComparisonRow[] {
  const projectModels = trainedModels.filter((m) => m.projectId === projectId);
  return projectModels.map((model) => {
    const spec = getModelCatalogEntry(model.architecture);
    const matchingReport = reports.find(
      (r) =>
        r.modelId === model.id &&
        r.datasetId === datasetId &&
        r.datasetVersion === datasetVersion &&
        r.split === split
    );
    const isMatchingSplit = Boolean(
      matchingReport || (model.datasetId === datasetId && model.datasetVersion === datasetVersion)
    );
    const primaryMetricName =
      model.taskType === 'object_detection' ? 'mAP50' : 'accuracy';
    const primaryMetricValue = matchingReport
      ? model.taskType === 'object_detection'
        ? matchingReport.mAP50
        : matchingReport.accuracy
      : model.taskType === 'object_detection'
      ? model.mAP50
      : model.accuracy;

    return {
      modelId: model.id,
      modelName: model.name,
      architecture: model.architecture,
      backendEngine: model.backendEngine,
      datasetId: matchingReport ? matchingReport.datasetId : model.datasetId,
      datasetVersion: matchingReport ? matchingReport.datasetVersion : model.datasetVersion,
      split: matchingReport ? matchingReport.split : 'val',
      isMatchingSplit,
      primaryMetricName,
      primaryMetricValue,
      f1Score: matchingReport ? matchingReport.f1Score : model.f1Score,
      precision: matchingReport ? matchingReport.precision : model.precision,
      recall: matchingReport ? matchingReport.recall : model.recall,
      avgLatencyMs: matchingReport ? matchingReport.avgLatencyMs : model.inferenceLatencyMs,
      weightSizeBytes: model.weightSizeBytes,
      parameterCount: model.parameterCount,
      upstreamReferenceBenchmark:
        spec?.officialReferenceBenchmark ?? 'Measured directly on your local dataset',
      preprocessMode: getPreprocessModeForArchitecture(model.architecture),
    };
  });
}
