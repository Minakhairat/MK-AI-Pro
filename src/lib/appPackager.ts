      function decodeBase64Buffer(b64) {
        const bin = atob(b64);
        const bytes = new Uint8Array(bin.length);
        for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i);
        return bytes.buffer;
      }

      async function ensureModel() {
        if (tfModel) return tfModel;
        if (!bundle.available) {
          throw new Error('Model weights are stored in cloud/Python worker or unavailable locally.');
        }
        const weightBuffer = decodeBase64Buffer(bundle.weightDataBase64);
        tfModel = await tf.loadLayersModel(tf.io.fromMemory({
          modelTopology: bundle.modelTopology,
          weightSpecs: bundle.weightSpecs,
          weightData: weightBuffer
        }));
        return tfModel;
      }

      function sigmoid(x) { return 1 / (1 + Math.exp(-x)); }

      function decodeGrid(raw, classes, gridSize, confThresh, iouThresh) {
        const stride = 5 + classes.length;
        const boxes = [];
        for (let gy = 0; gy < gridSize; gy++) {
          for (let gx = 0; gx < gridSize; gx++) {
            const offset = (gy * gridSize + gx) * stride;
            const obj = sigmoid(raw[offset + 4]);
            if (obj < 0.05) continue;
            let maxLogit = -Infinity;
            for (let c = 0; c < classes.length; c++) maxLogit = Math.max(maxLogit, raw[offset + 5 + c]);
            const exp = []; let sumExp = 0;
            for (let c = 0; c < classes.length; c++) {
              const e = Math.exp(raw[offset + 5 + c] - maxLogit);
              exp.push(e); sumExp += e;
            }
            let bestIdx = 0, bestProb = 0;
            for (let c = 0; c < classes.length; c++) {
              const p = (exp[c] / (sumExp || 1)) * obj;
              if (p > bestProb) { bestProb = p; bestIdx = c; }
            }
            if (bestProb < confThresh) continue;
            const cx = (gx + sigmoid(raw[offset])) / gridSize;
            const cy = (gy + sigmoid(raw[offset + 1])) / gridSize;
            const w = Math.min(1, Math.max(0.02, sigmoid(raw[offset + 2])));
            const h = Math.min(1, Math.max(0.02, sigmoid(raw[offset + 3])));
            boxes.push({
              className: classes[bestIdx],
              confidence: bestProb,
              x: Math.max(0, cx - w / 2),
              y: Math.max(0, cy - h / 2),
              width: w,
              height: h
            });
          }
        }
        boxes.sort((a, b) => b.confidence - a.confidence);
        const kept = [];
        for (const b of boxes) {
          const overlaps = kept.some((k) => {
            const x1 = Math.max(k.x, b.x), y1 = Math.max(k.y, b.y);
            const x2 = Math.min(k.x + k.width, b.x + b.width), y2 = Math.min(k.y + k.height, b.y + b.height);
            const inter = Math.max(0, x2 - x1) * Math.max(0, y2 - y1);
            const union = k.width * k.height + b.width * b.height - inter;
            return union > 0 && inter / union > iouThresh;
          });
          if (!overlaps) kept.push(b);
        }
        return kept;
      }

