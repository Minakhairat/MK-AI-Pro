function slugifyAppName(name: string): string {
  const cleaned = name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
  return cleaned || 'mk-vision-app';
}

function escapeHtml(text: string): string {
  return text
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

function safeJsonScriptContent(value: unknown): string {
  return JSON.stringify(value).replace(/</g, '\\u003c').replace(/>/g, '\\u003e');
}

function arrayBufferToBase64Portable(buffer: ArrayBuffer): string {
  const bytes = new Uint8Array(buffer);
  let binary = '';
  const chunkSize = 0x8000;
  for (let i = 0; i < bytes.length; i += chunkSize) {
    const slice = bytes.subarray(i, i + chunkSize);
    binary += String.fromCharCode(...slice);
  }
  return btoa(binary);
}

export function buildAppIconSvg(app: GeneratedApp): string {
  const hex = /^#[0-9a-fA-F]{6}$/.test(app.themeColor) ? app.themeColor : '#DC2626';
  const initials = escapeHtml(
    app.shortName
      .trim()
      .slice(0, 2)
      .toUpperCase() || 'MK'
  );
  const bg = app.backgroundColor === 'dark' ? '#09090B' : '#FFFFFF';
  const fg = app.backgroundColor === 'dark' ? '#FFFFFF' : '#09090B';

  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" fill="none">
  <rect width="512" height="512" rx="112" fill="${bg}" />
  <rect x="32" y="32" width="448" height="448" rx="88" stroke="${hex}" stroke-width="20" />
  <text x="256" y="294" text-anchor="middle" font-family="system-ui, -apple-system, sans-serif" font-size="168" font-weight="800" fill="${fg}">${initials}</text>
  <circle cx="396" cy="116" r="22" fill="${hex}" />
</svg>
`;
}

export function isValidCustomIconDataUrl(value?: string | null): boolean {
  if (!value) return false;
  return (
    value.length <= 150000 &&
    /^data:image\/(png|jpeg|webp);base64,[A-Za-z0-9+/=]+$/.test(value)
  );
}

