export function buildServiceWorkerJs(app: GeneratedApp): string {
  const slug = slugifyAppName(app.name);
  const cacheName = `mk-ai-${slug}-v${app.version}`;
  const iconAssets = isValidCustomIconDataUrl(app.customIconDataUrl)
    ? `  './app-icon.png',\n  './app-icon.svg',`
    : `  './app-icon.svg',`;
  return `// MK AI by MK Tech — Offline Service Worker for ${slug}
const CACHE_NAME = '${cacheName}';
const CORE_ASSETS = [
  './${slug}.html',
  './manifest.webmanifest',
${iconAssets}
];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => cache.addAll(CORE_ASSETS))
  );
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(keys.filter((k) => k !== CACHE_NAME).map((k) => caches.delete(k)))
    )
  );
  self.clients.claim();
});

self.addEventListener('fetch', (event) => {
  if (event.request.method !== 'GET') return;
  event.respondWith(
    caches.match(event.request).then((cached) => {
      if (cached) return cached;
      return fetch(event.request).then((response) => {
        const clone = response.clone();
        caches.open(CACHE_NAME).then((cache) => cache.put(event.request, clone));
        return response;
      });
    })
  );
});
`;
}

